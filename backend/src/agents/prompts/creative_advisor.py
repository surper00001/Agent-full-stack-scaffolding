def get_prompt_for_agent(agent_type: str) -> str:
    """根据 Agent 类型返回对应的系统提示词。"""
    prompts = {
        "creative": CREATIVE_ADVISOR_PROMPT,
        "creative_director": CREATIVE_ADVISOR_PROMPT,
    }
    return prompts.get(agent_type, "你是一个智能助手，请根据用户需求提供专业帮助。")
